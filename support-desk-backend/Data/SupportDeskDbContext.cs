using Microsoft.EntityFrameworkCore;
using SupportDesk.Api.Domain;

namespace SupportDesk.Api.Data;

public sealed class SupportDeskDbContext(DbContextOptions<SupportDeskDbContext> options) : DbContext(options)
{
    public DbSet<Ticket> Tickets => Set<Ticket>();

    public DbSet<TicketComment> TicketComments => Set<TicketComment>();

    public DbSet<TicketStatusChange> TicketStatusChanges => Set<TicketStatusChange>();

    protected override void ConfigureConventions(ModelConfigurationBuilder configurationBuilder)
    {
        configurationBuilder
            .Properties<DateTimeOffset>()
            .HaveConversion<DateTimeOffsetToUtcTicksConverter>();
    }

    protected override void OnModelCreating(ModelBuilder modelBuilder)
    {
        modelBuilder.Entity<Ticket>(entity =>
        {
            entity.HasKey(ticket => ticket.Id);
            // Ids are generated by the domain (Guid v7), so EF must not treat a set key as an existing row.
            entity.Property(ticket => ticket.Id).ValueGeneratedNever();
            entity.Property(ticket => ticket.Title).HasMaxLength(TicketConstraints.TitleMaxLength).IsRequired();
            entity.Property(ticket => ticket.Description).HasMaxLength(TicketConstraints.DescriptionMaxLength).IsRequired();
            entity.Property(ticket => ticket.Status).HasConversion<string>().HasMaxLength(32);
            entity.Property(ticket => ticket.Priority).HasConversion<string>().HasMaxLength(16);
            entity.Property(ticket => ticket.CustomerName).HasMaxLength(TicketConstraints.CustomerNameMaxLength);
            entity.Property(ticket => ticket.CustomerEmail).HasMaxLength(TicketConstraints.CustomerEmailMaxLength);
            // Every write sets UpdatedAt, so it doubles as an optimistic concurrency token:
            // EF adds "WHERE UpdatedAt = <loaded value>" to UPDATE/DELETE statements.
            entity.Property(ticket => ticket.UpdatedAt).IsConcurrencyToken();
            entity.HasIndex(ticket => ticket.CreatedAt);
            entity.HasMany(ticket => ticket.Comments)
                .WithOne(comment => comment.Ticket)
                .HasForeignKey(comment => comment.TicketId)
                .OnDelete(DeleteBehavior.Cascade);
            entity.HasMany(ticket => ticket.StatusChanges)
                .WithOne(change => change.Ticket)
                .HasForeignKey(change => change.TicketId)
                .OnDelete(DeleteBehavior.Cascade);
        });

        modelBuilder.Entity<TicketComment>(entity =>
        {
            entity.HasKey(comment => comment.Id);
            entity.Property(comment => comment.Id).ValueGeneratedNever();
            entity.Property(comment => comment.Text).HasMaxLength(TicketConstraints.CommentMaxLength).IsRequired();
            entity.Property(comment => comment.Author).HasMaxLength(TicketConstraints.AuthorMaxLength).IsRequired();
        });

        modelBuilder.Entity<TicketStatusChange>(entity =>
        {
            entity.HasKey(change => change.Id);
            entity.Property(change => change.Id).ValueGeneratedNever();
            entity.Property(change => change.PreviousStatus).HasConversion<string>().HasMaxLength(32);
            entity.Property(change => change.NewStatus).HasConversion<string>().HasMaxLength(32);
            entity.Property(change => change.Author).HasMaxLength(TicketConstraints.AuthorMaxLength).IsRequired();
        });
    }
}
